// 長い表記から先に置き換える（'SUMIFS' を 'SUM' より先に処理するため）
const TTS_READING_KEYS = Object.keys(TTS_READINGS).sort((a, b) => b.length - a.length);
const TTS_READING_RE = new RegExp(
  TTS_READING_KEYS.map(k => {
    const esc = k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    // 英字だけの語は、別の英単語の一部（例：'IF' が 'DIFF' の中）を置き換えないよう境界を付ける
    return /^[A-Za-z]/.test(k) ? `(?<![A-Za-z0-9])${esc}(?![A-Za-z0-9])` : esc;
  }).join('|'),
  'g'
);

// 数字（0〜9999）を読み仮名にする。「1位」を「いちい」と読ませるために使う。
function numberToKana(n) {
  if (n === 0) return 'ぜろ';
  const ones = ['', 'いち', 'に', 'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう'];
  const hundreds = ['', 'ひゃく', 'にひゃく', 'さんびゃく', 'よんひゃく', 'ごひゃく', 'ろっぴゃく', 'ななひゃく', 'はっぴゃく', 'きゅうひゃく'];
  const thousands = ['', 'せん', 'にせん', 'さんぜん', 'よんせん', 'ごせん', 'ろくせん', 'ななせん', 'はっせん', 'きゅうせん'];
  const t = Math.floor(n / 1000) % 10, h = Math.floor(n / 100) % 10;
  const te = Math.floor(n / 10) % 10, o = n % 10;
  const tens = te === 0 ? '' : (te === 1 ? 'じゅう' : ones[te] + 'じゅう');
  return thousands[t] + hundreds[h] + tens + ones[o];
}

// 単独の英字1文字（16進数の「A」「F」など）はアルファベット名で読ませる
const TTS_LETTER_NAMES = {
  A: 'エー', B: 'ビー', C: 'シー', D: 'ディー', E: 'イー', F: 'エフ', G: 'ジー', H: 'エイチ', I: 'アイ',
  J: 'ジェイ', K: 'ケー', L: 'エル', M: 'エム', N: 'エヌ', O: 'オー', P: 'ピー', Q: 'キュー', R: 'アール',
  S: 'エス', T: 'ティー', U: 'ユー', V: 'ブイ', W: 'ダブリュー', X: 'エックス', Y: 'ワイ', Z: 'ゼット',
};

function speechText(text) {
  return String(text)
    // CPU名の先頭0（強CPU02 など）は読まない
    .replace(/(強|中|弱)CPU0(\d)/g, '$1CPU$2')
    // 「1位」「12位」→「いちい」「じゅうにい」（そのままだと「〜くらい」と読まれる）
    .replace(/(\d{1,4})位/g, (_, d) => numberToKana(parseInt(d, 10)) + 'い')
    // 表記→読み仮名の辞書（札→ふだ、英字の略語→カタカナ など）
    .replace(TTS_READING_RE, m => TTS_READINGS[m])
    .replace(/(?<![A-Za-z0-9])([A-Z])(?![A-Za-z0-9])/g, (_, c) => TTS_LETTER_NAMES[c]);
}

function newUtterance(text) {
  return new SpeechSynthesisUtterance(speechText(text));
}

